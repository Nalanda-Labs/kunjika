//! Applies the SQL migrations in `backend/migrations/` when the backend
//! starts, so deploying a new build is enough to bring the database up to
//! date.
//!
//! The files are compiled into the binary by `build.rs`. Bookkeeping is the
//! `kunjika_migrations` table that `migrations/run_migrations.py` already
//! uses (same versions, same SHA-256 checksums), so the two are
//! interchangeable: a database migrated by one is seen as up to date by the
//! other.
//!
//! Rules, the same as the script's:
//!   * migrations run in version order, each statement in its own autocommit
//!     (YugabyteDB does not roll back DDL, which is why every migration is
//!     written to be re-runnable);
//!   * a migration is recorded only after all of it has run, so a failed one
//!     is retried on the next start;
//!   * a file that was edited after being applied is reported and NOT re-run.
//!
//! One migration uses psql commands (`\gset`, `\if`). The script handles
//! that by shelling out to `psql`; here the handful of commands in use are
//! interpreted directly (see [`parse`]), so the server does not need `psql`
//! installed.
//!
//! What this cannot do is the very first build: sqlx checks queries against
//! a migrated database at COMPILE time, so a development machine or CI still
//! needs `run_migrations.py` before `cargo build`.

use std::collections::HashMap;

use ring::digest::{digest, SHA256};
use sqlx::postgres::PgConnection;
use sqlx::{AssertSqlSafe, Row};

use crate::state::SqlPool;

pub struct Migration {
    pub version: i64,
    pub description: &'static str,
    pub sql: &'static [u8],
}

/// Every migration, in version order (generated by `build.rs`).
pub static MIGRATIONS: &[Migration] = include!(concat!(env!("OUT_DIR"), "/migrations.rs"));

const TABLE: &str = "kunjika_migrations";
/// Arbitrary constant: the advisory lock that makes concurrent starts take
/// turns migrating.
const LOCK_KEY: i64 = 0x6b75_6e6a_696b_61; // "kunjika"
/// How long to wait for another instance to finish migrating before giving
/// up. Building the whole schema from empty takes well under a minute.
const LOCK_WAIT_SECS: u64 = 600;

impl Migration {
    /// Hex SHA-256 of the file, as `run_migrations.py` records it.
    pub fn checksum(&self) -> String {
        hex::encode(digest(&SHA256, self.sql))
    }
}

/// One step of a migration file.
#[derive(Debug, PartialEq, Eq, Clone)]
pub enum Step {
    /// A statement to execute.
    Sql(String),
    /// A query whose single result row is stored into variables named after
    /// its columns (psql `\gset`).
    Gset(String),
    /// psql `\if :name`: run the following steps only when the variable is true.
    If(String),
    Else,
    EndIf,
    /// psql `\echo`: a message for the log.
    Echo(String),
}

/// Split a migration file into steps.
///
/// Statements end at a top-level `;`. Semicolons inside string literals,
/// quoted identifiers, dollar-quoted bodies (`$$ ... $$`, `$tag$ ... $tag$`)
/// and comments do not count. A line that starts with a backslash is a psql
/// command; only the ones the migrations use are understood, and any other
/// is an error rather than something to skip silently.
pub fn parse(source: &str) -> Result<Vec<Step>, String> {
    let chars: Vec<char> = source.chars().collect();
    let mut steps = Vec::new();
    let mut buf = String::new();
    let mut i = 0;
    let mut line_start = true;

    // The text gathered so far, if it holds anything besides whitespace and
    // comments (which were not copied into it).
    fn take(buf: &mut String) -> Option<String> {
        let s = buf.trim().to_string();
        buf.clear();
        (!s.is_empty()).then_some(s)
    }

    while i < chars.len() {
        let c = chars[i];

        // A psql command: a backslash first on its line.
        if line_start && c == '\\' {
            let end = chars[i..].iter().position(|&c| c == '\n').map_or(chars.len(), |p| i + p);
            let line: String = chars[i + 1..end].iter().collect();
            let (name, rest) = match line.split_once(char::is_whitespace) {
                Some((n, r)) => (n, r.trim()),
                None => (line.trim(), ""),
            };
            match name {
                "gset" => match take(&mut buf) {
                    Some(sql) => steps.push(Step::Gset(sql)),
                    None => return Err("\\gset with no query before it".into()),
                },
                "if" | "else" | "endif" | "echo" => {
                    if let Some(sql) = take(&mut buf) {
                        return Err(format!("statement not terminated before \\{name}: {sql}"));
                    }
                    steps.push(match name {
                        "if" => Step::If(rest.to_string()),
                        "else" => Step::Else,
                        "endif" => Step::EndIf,
                        _ => Step::Echo(rest.trim_matches('\'').to_string()),
                    });
                }
                other => return Err(format!("unsupported psql command \\{other}")),
            }
            i = end;
            continue;
        }

        match c {
            '\n' => {
                buf.push(c);
                line_start = true;
                i += 1;
                continue;
            }
            // -- comment: dropped, up to the end of the line.
            '-' if chars.get(i + 1) == Some(&'-') => {
                while i < chars.len() && chars[i] != '\n' {
                    i += 1;
                }
                continue;
            }
            // /* comment */, which PostgreSQL allows to nest.
            '/' if chars.get(i + 1) == Some(&'*') => {
                let mut depth = 0;
                while i < chars.len() {
                    if chars[i] == '/' && chars.get(i + 1) == Some(&'*') {
                        depth += 1;
                        i += 2;
                    } else if chars[i] == '*' && chars.get(i + 1) == Some(&'/') {
                        depth -= 1;
                        i += 2;
                        if depth == 0 {
                            break;
                        }
                    } else {
                        i += 1;
                    }
                }
                buf.push(' ');
                line_start = false;
                continue;
            }
            // 'string' or "identifier": copied whole. A doubled quote inside
            // is an escaped quote, which this loop passes over naturally (it
            // closes and immediately reopens).
            '\'' | '"' => {
                buf.push(c);
                i += 1;
                while i < chars.len() {
                    buf.push(chars[i]);
                    i += 1;
                    if chars[i - 1] == c {
                        break;
                    }
                }
            }
            // $tag$ body $tag$: copied whole. `$1` is a parameter, not a tag.
            '$' => {
                let tag_end = chars[i + 1..]
                    .iter()
                    .position(|&c| !(c.is_alphanumeric() || c == '_'))
                    .map(|p| i + 1 + p);
                let is_tag = matches!(tag_end, Some(e) if chars[e] == '$')
                    && !chars.get(i + 1).is_some_and(|c| c.is_ascii_digit());
                if let (true, Some(e)) = (is_tag, tag_end) {
                    let tag: String = chars[i..=e].iter().collect();
                    let body_start = e + 1;
                    let rest: String = chars[body_start..].iter().collect();
                    let Some(close) = rest.find(&tag) else {
                        return Err(format!("unterminated dollar-quoted string {tag}"));
                    };
                    let body_len = rest[..close].chars().count();
                    let end = body_start + body_len + tag.chars().count();
                    buf.extend(&chars[i..end]);
                    i = end;
                } else {
                    buf.push(c);
                    i += 1;
                }
            }
            ';' => {
                i += 1;
                if let Some(sql) = take(&mut buf) {
                    steps.push(Step::Sql(sql));
                }
            }
            _ => {
                buf.push(c);
                i += 1;
            }
        }
        if !c.is_whitespace() {
            line_start = false;
        }
    }
    // A last statement without its semicolon still counts.
    if let Some(sql) = take(&mut buf) {
        steps.push(Step::Sql(sql));
    }
    Ok(steps)
}

/// psql's reading of a boolean variable in `\if`.
fn truthy(value: &str) -> bool {
    matches!(value.trim().to_ascii_lowercase().as_str(), "t" | "true" | "on" | "1" | "y" | "yes")
}

/// Run one migration's steps on `conn`, each statement on its own.
async fn execute(conn: &mut PgConnection, steps: &[Step]) -> Result<(), String> {
    let mut vars: HashMap<String, String> = HashMap::new();
    // One entry per open `\if`: whether its current branch is being run.
    // Steps run only while every enclosing branch is live.
    let mut branches: Vec<bool> = Vec::new();

    for step in steps {
        let live = branches.iter().all(|&b| b);
        match step {
            Step::If(expr) => {
                let name = expr.trim().trim_start_matches(':');
                let value = vars
                    .get(name)
                    .ok_or_else(|| format!("\\if uses :{name}, which no \\gset has set"))?;
                branches.push(truthy(value));
            }
            Step::Else => {
                let last = branches.last_mut().ok_or("\\else without \\if")?;
                *last = !*last;
            }
            Step::EndIf => {
                branches.pop().ok_or("\\endif without \\if")?;
            }
            Step::Echo(message) if live => info!("migration: {message}"),
            Step::Sql(sql) if live => {
                sqlx::raw_sql(AssertSqlSafe(sql.clone()))
                    .execute(&mut *conn)
                    .await
                    .map_err(|e| format!("{e}\n  in statement: {}", first_line(sql)))?;
            }
            Step::Gset(sql) if live => {
                let row = sqlx::raw_sql(AssertSqlSafe(sql.clone()))
                    .fetch_one(&mut *conn)
                    .await
                    .map_err(|e| format!("{e}\n  in query: {}", first_line(sql)))?;
                for (index, column) in row.columns().iter().enumerate() {
                    // psql stores every value as text; booleans as t / f.
                    let value = if let Ok(v) = row.try_get::<bool, _>(index) {
                        if v { "t" } else { "f" }.to_string()
                    } else if let Ok(v) = row.try_get::<i64, _>(index) {
                        v.to_string()
                    } else if let Ok(v) = row.try_get::<String, _>(index) {
                        v
                    } else {
                        return Err(format!(
                            "\\gset: column {} has a type this migrator cannot read",
                            sqlx::Column::name(column)
                        ));
                    };
                    vars.insert(sqlx::Column::name(column).to_string(), value);
                }
            }
            _ => {} // inside a branch that is not taken
        }
    }
    if !branches.is_empty() {
        return Err("\\if without \\endif".into());
    }
    Ok(())
}

fn first_line(sql: &str) -> String {
    let line = sql.lines().next().unwrap_or("");
    line.chars().take(160).collect()
}

/// What [`run`] did.
#[derive(Debug, PartialEq, Eq)]
pub enum Outcome {
    /// Nothing was pending.
    UpToDate,
    /// This many migrations were applied.
    Applied(usize),
    /// The database has the schema but no record of how it got there; see
    /// the error logged by [`run`]. Nothing was changed.
    NeedsBaseline,
}

/// Bring the database up to date. Called once at startup, before the pool is
/// used for anything else. `Err` means a migration failed part-way: the
/// caller must not go on to serve requests against a half-migrated schema.
pub async fn run(pool: &SqlPool) -> Result<Outcome, String> {
    let db = |e: sqlx::Error| e.to_string();
    // One connection throughout: the advisory lock belongs to the session.
    let mut conn = pool.acquire().await.map_err(db)?;

    // Two backends starting together must not both run the same migration,
    // so they take turns on an advisory lock.
    //
    // The lock is POLLED with `pg_try_advisory_lock`, never waited for with
    // `pg_advisory_lock`. On YugabyteDB a session blocked inside the database
    // counts as an open transaction, and `CREATE INDEX` (online there) waits
    // for every open transaction to finish before it completes. A second
    // backend blocked on the lock would therefore stall the first one's
    // migration, which holds the lock: both hang for good. Between polls
    // this session is idle and holds nothing up.
    //
    // If advisory locks are not available at all, carry on without one: the
    // migrations themselves are written to be re-runnable.
    let mut locked = false;
    let mut waited = 0u64;
    loop {
        match sqlx::query_scalar::<_, bool>("select pg_try_advisory_lock($1)")
            .bind(LOCK_KEY)
            .fetch_one(&mut *conn)
            .await
        {
            Ok(true) => {
                locked = true;
                break;
            }
            Ok(false) if waited >= LOCK_WAIT_SECS => {
                return Err(format!(
                    "another process has held the migration lock for {LOCK_WAIT_SECS}s. If no \
                     other backend is starting, a session left behind by one that was killed \
                     mid-migration still holds it; end that database session and start again."
                ));
            }
            Ok(false) => {
                if waited % 10 == 0 {
                    info!("migrations: another instance is migrating, waiting for it to finish");
                }
                ntex::time::sleep(ntex::time::Seconds(1)).await;
                waited += 1;
            }
            Err(e) => {
                warn!("migrations: no advisory lock, continuing without one: {e}");
                break;
            }
        }
    }

    let result = migrate(&mut conn).await;

    if locked {
        let _ = sqlx::query("select pg_advisory_unlock($1)")
            .bind(LOCK_KEY)
            .execute(&mut *conn)
            .await;
    }
    result
}

async fn migrate(conn: &mut PgConnection) -> Result<Outcome, String> {
    let db = |e: sqlx::Error| e.to_string();

    sqlx::raw_sql(AssertSqlSafe(format!(
        "create table if not exists {TABLE} (
            version     bigint primary key,
            description text not null,
            checksum    text not null,
            applied_at  timestamptz not null default now()
        )"
    )))
    .execute(&mut *conn)
    .await
    .map_err(db)?;

    let applied: HashMap<i64, String> =
        sqlx::query(AssertSqlSafe(format!("select version, checksum from {TABLE}")))
            .fetch_all(&mut *conn)
            .await
            .map_err(db)?
            .into_iter()
            .map(|r| (r.get::<i64, _>(0), r.get::<String, _>(1).trim().to_string()))
            .collect();

    // A database that was set up by hand has the tables but an empty
    // bookkeeping table. Running the first migration against it would fail
    // half-way through on objects that already exist, so leave it alone and
    // say what to do instead.
    if applied.is_empty() {
        let has_schema: bool = sqlx::query_scalar("select to_regclass('public.users') is not null")
            .fetch_one(&mut *conn)
            .await
            .map_err(db)?;
        if has_schema {
            error!(
                "migrations: this database already has the schema but no migration history, so \
                 nothing was applied automatically. Record what is already in place with \
                 `backend/migrations/run_migrations.py --baseline` (after checking which \
                 migrations the schema really includes), then restart."
            );
            return Ok(Outcome::NeedsBaseline);
        }
    }

    let mut count = 0;
    for m in MIGRATIONS {
        let checksum = m.checksum();
        match applied.get(&m.version) {
            Some(recorded) if *recorded == checksum => continue,
            Some(_) => {
                warn!(
                    "migrations: {}_{} was changed after it was applied; not re-running it",
                    m.version, m.description
                );
                continue;
            }
            None => {}
        }

        info!("migrations: applying {}_{}", m.version, m.description);
        let source = std::str::from_utf8(m.sql)
            .map_err(|e| format!("{}_{} is not UTF-8: {e}", m.version, m.description))?;
        let steps = parse(source).map_err(|e| format!("{}_{}: {e}", m.version, m.description))?;
        execute(conn, &steps).await.map_err(|e| {
            format!(
                "migration {}_{} failed: {e}\n  It was not recorded, so it will be retried on the \
                 next start. Statements before the failing one are already in effect.",
                m.version, m.description
            )
        })?;
        sqlx::query(AssertSqlSafe(format!(
            "insert into {TABLE} (version, description, checksum) values ($1, $2, $3)"
        )))
        .bind(m.version)
        .bind(m.description)
        .bind(&checksum)
        .execute(&mut *conn)
        .await
        .map_err(db)?;
        count += 1;
    }

    Ok(if count == 0 { Outcome::UpToDate } else { Outcome::Applied(count) })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sql(steps: &[Step]) -> Vec<&str> {
        steps
            .iter()
            .map(|s| match s {
                Step::Sql(s) => s.as_str(),
                other => panic!("expected only statements, got {other:?}"),
            })
            .collect()
    }

    #[test]
    fn splits_on_top_level_semicolons_only() {
        let steps = parse(
            "CREATE TABLE a (x text DEFAULT 'a;b');\n\
             -- a comment; with a semicolon\n\
             INSERT INTO a VALUES ('it''s; fine'); /* block; comment */ SELECT \"odd;name\" FROM a;\n\
             SELECT 1",
        )
        .unwrap();
        assert_eq!(
            sql(&steps),
            [
                "CREATE TABLE a (x text DEFAULT 'a;b')",
                "INSERT INTO a VALUES ('it''s; fine')",
                "SELECT \"odd;name\" FROM a",
                "SELECT 1",
            ]
        );
    }

    #[test]
    fn keeps_dollar_quoted_bodies_whole() {
        let steps = parse(
            "CREATE FUNCTION f() RETURNS trigger AS $$\n  BEGIN\n    DELETE FROM t; -- inside\n    RETURN NEW;\n  END;\n$$ LANGUAGE plpgsql;\n\
             DO $body$ BEGIN PERFORM 1; EXECUTE 'select $$x$$'; END $body$;\n\
             SELECT $1::int;",
        )
        .unwrap();
        let s = sql(&steps);
        assert_eq!(s.len(), 3, "{s:?}");
        assert!(s[0].ends_with("$$ LANGUAGE plpgsql") && s[0].contains("DELETE FROM t; -- inside"));
        assert!(s[1].starts_with("DO $body$") && s[1].ends_with("$body$"));
        assert_eq!(s[2], "SELECT $1::int");
        assert!(parse("DO $$ BEGIN").is_err(), "an unterminated body is an error");
    }

    #[test]
    fn understands_the_psql_commands_the_migrations_use() {
        let steps = parse(
            "SELECT EXISTS (SELECT 1) AS done\n\\gset\n\n\\if :done\n\\echo 'nothing to do'\n\\else\n\
             DROP TABLE a;\nCREATE TABLE a (x int);\n\\endif\nSELECT 2;",
        )
        .unwrap();
        assert_eq!(
            steps,
            [
                Step::Gset("SELECT EXISTS (SELECT 1) AS done".into()),
                Step::If(":done".into()),
                Step::Echo("nothing to do".into()),
                Step::Else,
                Step::Sql("DROP TABLE a".into()),
                Step::Sql("CREATE TABLE a (x int)".into()),
                Step::EndIf,
                Step::Sql("SELECT 2".into()),
            ]
        );
        // Anything else is refused, not skipped.
        assert!(parse("\\copy a from 'x'").unwrap_err().contains("\\copy"));
        assert!(parse("\\gset").is_err());
        // A backslash that is not first on its line is ordinary text.
        assert_eq!(sql(&parse("SELECT E'a\\nb';").unwrap()), ["SELECT E'a\\nb'"]);
    }

    #[test]
    fn every_embedded_migration_parses() {
        assert!(!MIGRATIONS.is_empty());
        let mut last = 0;
        for m in MIGRATIONS {
            assert!(m.version > last, "migrations must be in version order");
            last = m.version;
            let source = std::str::from_utf8(m.sql).unwrap();
            let steps = parse(source).unwrap_or_else(|e| panic!("{}_{}: {e}", m.version, m.description));
            assert!(!steps.is_empty(), "{}_{} is empty", m.version, m.description);
            assert_eq!(m.checksum().len(), 64);
            // Balanced \if / \endif.
            let depth = steps.iter().fold(0i32, |d, s| match s {
                Step::If(_) => d + 1,
                Step::EndIf => d - 1,
                _ => d,
            });
            assert_eq!(depth, 0, "{}_{}", m.version, m.description);
        }
    }

    #[test]
    fn psql_booleans() {
        for yes in ["t", "true", "TRUE", "on", "1", "yes"] {
            assert!(truthy(yes), "{yes}");
        }
        for no in ["f", "false", "off", "0", "", "no"] {
            assert!(!truthy(no), "{no}");
        }
    }
}
